import assert from 'node:assert/strict';
import fs from 'node:fs';
import {positionView} from '../docs/live-position.js';
const now=Date.parse('2026-10-12T11:00:00+08:00'),quote={date:'2026-10-12',time:'11:00:00',price:20};
const snapshot={valuationDate:quote.date,conditionalAccount:{status:'conditional',sourceSession:'2026-10-09',shares:100,available:80,cash:-500}};
const a=positionView(snapshot,{quote},{now});
assert.equal(a.status,'conditional');assert.match(a.acceptedMessage,/待验收/);
assert.deepEqual(a.metrics,{shares:100,available:80,marketValue:2000,equity:1500,weight:2000/1500,cash:0,debt:500,netCash:-500,carryInterest:0});
const b=positionView(snapshot,{quote:{...quote,price:25}},{now});
assert.equal(b.metrics.marketValue,2500);assert.equal(b.metrics.equity,2000);assert.equal(b.metrics.weight,1.25);assert.equal(b.metrics.debt,500);assert.equal(b.metrics.shares,100);assert.equal(b.metrics.available,80);
assert.equal(positionView(snapshot,{quote},{now,cached:true}).stale,true);
assert.equal(positionView(snapshot,{quote},{now:now+301000}).stale,true);
assert.equal(positionView(snapshot,{quote:{...quote,date:'2026-10-13'}},{now}).metrics,null);
assert.equal(positionView({...snapshot,conditionalAccount:null},{quote},{now}).metrics,null);
assert.equal(positionView({...snapshot,conditionalAccount:{...snapshot.conditionalAccount,available:101}},{quote},{now}).metrics,null);
assert.equal(positionView(snapshot,{quote:{...quote,price:Infinity}},{now}).metrics,null);
assert.equal(positionView(snapshot,{quote:{...quote,price:4}},{now}).metrics.weight,null);
const accepted={...snapshot,acceptedAccount:{status:'verified',sourceSession:'2026-10-12',asOf:'2026-10-12T10:55:00+08:00',shares:50,available:0,cash:400}};
assert.equal(positionView(accepted,{quote},{now}).status,'verified');assert.equal(positionView(accepted,{quote},{now}).metrics.available,0);
const published=JSON.parse(fs.readFileSync('docs/live-position.json'));
const actual=positionView(published,{quote:{...quote,price:112.29}},{now});
assert.equal(actual.status,'conditional');assert.equal(actual.metrics.shares,175700);assert.equal(actual.metrics.debt,7098554.395975726);
assert.ok(Math.abs(actual.metrics.equity-(175700*112.29-7098554.395975726))<1e-7);
console.log('PASS: price marking preserves shares/debt/T+1 availability; conditional/accepted states, stale prices, wrong dates, invalid fields and nonpositive equity distinguished.');
